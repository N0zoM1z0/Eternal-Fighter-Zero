#!/usr/bin/env python3
"""Generate the small public progress report from independent ledgers."""
import argparse
from common import ROOT
from tracking import summary


def render() -> str:
    result = summary()
    return f'''# Reconstruction progress

Generated by `scripts/repo-python scripts/progress.py` from `config/*.csv`.

| Fact | Count / state |
| --- | ---: |
| Ghidra function candidates | {result["candidate_functions"]} |
| Reviewed complete boundaries | {result["reviewed_boundaries"]} |
| Reviewed origins | {result["reviewed_origins"]} |
| Source functions | {result["source_functions"]} |
| Complete exact functions | {result["exact_functions"]} |
| Complete exact code bytes | {result["exact_bytes"]} |
| Associated exact local-table bytes | {result["exact_local_data_bytes"]} |
| Whole Windows product | open |
| Original / reconstructed runtime comparison | open |
| Portability | not started |

Candidates are an automatic inventory, not a reviewed authored-code denominator.
No whole-game completion percentage is claimed. Exact codegen does not establish
callee implementations, original TU partitioning, linked data, or runtime closure.
Local tables are compared with their complete function contribution and counted
separately from instruction bytes.
'''


def render_svg() -> str:
    result = summary()
    total = result["candidate_functions"]
    reviewed = result["reviewed_boundaries"]
    width = 512 * reviewed / total if total else 0
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="560" height="176" role="img" aria-label="EFZ reconstruction: {result['exact_functions']} exact functions, {result['exact_bytes']} exact bytes; {reviewed} reviewed boundaries out of {total} candidates">
  <rect width="560" height="176" rx="8" fill="#1f2335"/>
  <text x="24" y="28" fill="#f4f4f5" font-family="sans-serif" font-size="16" font-weight="600">EFZ reconstruction progress</text>
  <text x="24" y="55" fill="#f4f4f5" font-family="sans-serif" font-size="13" font-weight="600">Complete exact code</text>
  <text x="536" y="55" fill="#c7a4ff" text-anchor="end" font-family="monospace" font-size="13">{result['exact_functions']} functions / {result['exact_bytes']} bytes</text>
  <text x="24" y="78" fill="#c8cad2" font-family="sans-serif" font-size="12">Native product and runtime validation remain open</text>
  <text x="24" y="108" fill="#f4f4f5" font-family="sans-serif" font-size="13" font-weight="600">Reviewed complete boundaries</text>
  <text x="536" y="108" fill="#f4f4f5" text-anchor="end" font-family="monospace" font-size="13">{reviewed} / {total} candidates</text>
  <rect x="24" y="118" width="512" height="12" rx="6" fill="#3b4058"/>
  <rect x="24" y="118" width="{width:.2f}" height="12" rx="0.5" fill="#9b6de3"/>
  <text x="24" y="154" fill="#c8cad2" font-family="sans-serif" font-size="12">Initial checkpoint; whole-game authored coverage is not established</text>
</svg>
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in [(ROOT / "docs/PROGRESS.md", render()),
                           (ROOT / "resources/progress.svg", render_svg())]:
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                parser.exit(1, "progress report/card is stale; run scripts/progress.py\n")
        else:
            path.write_text(expected)
    print("progress report OK")
